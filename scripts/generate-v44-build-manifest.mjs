import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedModulePath = path.join(
  root,
  "lib",
  "v44-build-manifest.generated.ts",
);
const publicManifestPath = path.join(
  root,
  "public",
  "agentpool-v44-build-manifest.json",
);
const excluded = new Set([
  "lib/v44-build-manifest.generated.ts",
  "public/agentpool-v44-build-manifest.json",
]);
const gitShaPattern = /^[0-9a-f]{40}$/u;
const sha256Pattern = /^[0-9a-f]{64}$/u;

function sha256Bytes(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (value && typeof value === "object") {
    return `{${Object.entries(value)
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([key, nested]) => `${JSON.stringify(key)}:${canonicalJson(nested)}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

function gitOutput(args) {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "";
  }
}

function gitBytes(args) {
  return execFileSync("git", args, {
    cwd: root,
    encoding: "buffer",
    stdio: ["ignore", "pipe", "ignore"],
  });
}

function trackedFiles() {
  const listed = gitOutput(["ls-files", "-z"]);
  if (!listed) {
    throw new Error("V44_BUILD_MANIFEST_GIT_FILE_LIST_UNAVAILABLE");
  }
  return listed
    .split("\0")
    .filter(Boolean)
    .map((entry) => entry.replaceAll("\\", "/"))
    .filter((entry) => !excluded.has(entry))
    .sort();
}

const gitCommit = gitOutput(["rev-parse", "HEAD"]).toLowerCase();
const interfaceSourceCommit = (
  process.env.AGENTPOOL_INTERFACE_SOURCE_COMMIT?.trim().toLowerCase() ||
  gitCommit
);
const siteBuildCommit = (
  process.env.AGENTPOOL_SITE_BUILD_COMMIT?.trim().toLowerCase() ||
  gitCommit
);
const sourceTreeArchiveSha256 =
  process.env.AGENTPOOL_SOURCE_ARCHIVE_SHA256?.trim().toLowerCase() || null;
const siteDeploymentVersion =
  process.env.AGENTPOOL_SITE_DEPLOYMENT_VERSION?.trim() || null;

if (
  !gitShaPattern.test(interfaceSourceCommit) ||
  !gitShaPattern.test(siteBuildCommit) ||
  interfaceSourceCommit !== siteBuildCommit ||
  (gitCommit && gitCommit !== interfaceSourceCommit) ||
  (sourceTreeArchiveSha256 !== null &&
    !sha256Pattern.test(sourceTreeArchiveSha256))
) {
  throw new Error("V44_BUILD_MANIFEST_PROVENANCE_INPUT_INVALID");
}

const generatedFromCleanTree =
  gitOutput(["status", "--porcelain", "--untracked-files=no"]) === "";
const files = trackedFiles().map((relativePath) => {
  return {
    path: relativePath,
    sha256: sha256Bytes(
      gitBytes(["show", `${interfaceSourceCommit}:${relativePath}`]),
    ),
  };
});
const sourceTreeManifestRoot = sha256Bytes(
  Buffer.from(canonicalJson(files), "utf8"),
);
const body = {
  schema: "agentpool.v44.interface-build-manifest/v1",
  interfaceSourceCommit,
  siteBuildCommit,
  siteDeploymentVersion,
  sourceTreeArchiveSha256,
  generatedFromCleanTree,
  sourceTreeManifestRoot,
  sourceFiles: files,
  canonicalSourceRef: `https://github.com/agentpool-protocol/agentpool/tree/${interfaceSourceCommit}`,
};
const buildManifestSha256 = sha256Bytes(
  Buffer.from(canonicalJson(body), "utf8"),
);
const manifest = { ...body, buildManifestSha256 };
const publicManifestBytes = Buffer.from(
  `${JSON.stringify(manifest, null, 2)}\n`,
  "utf8",
);
const buildManifestFileSha256 = sha256Bytes(publicManifestBytes);

fs.mkdirSync(path.dirname(generatedModulePath), { recursive: true });
fs.mkdirSync(path.dirname(publicManifestPath), { recursive: true });
fs.writeFileSync(
  generatedModulePath,
  `// Generated by scripts/generate-v44-build-manifest.mjs\nexport const V44_BUILD_MANIFEST = ${JSON.stringify(
    {
      ...manifest,
      sourceFiles: undefined,
      sourceFileCount: files.length,
      buildManifestFileSha256,
    },
    null,
    2,
  )} as const;\n`,
  "utf8",
);
fs.writeFileSync(
  publicManifestPath,
  publicManifestBytes,
);
process.stdout.write(
  `${JSON.stringify({
    interfaceSourceCommit,
    sourceTreeManifestRoot,
    buildManifestSha256,
    buildManifestFileSha256,
    sourceFileCount: files.length,
  })}\n`,
);
